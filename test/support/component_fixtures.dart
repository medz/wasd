/// Rewrites a decoded `stream<u32>` or `future<u32>` memory-copy program to
/// use `own resource` element handles at component type index 2.
Uint8List ownedResourceAsyncMemoryProgramFromU32(
  Uint8List source, {
  required bool isStream,
}) {
  final bytes = source.toList();
  final oldTypeSection = isStream
      ? const <int>[0x07, 0x04, 0x01, 0x66, 0x01, 0x79]
      : const <int>[0x07, 0x04, 0x01, 0x65, 0x01, 0x79];
  final newTypeSection = isStream
      ? const <int>[
          0x07,
          0x09,
          0x03,
          0x3f,
          0x7f,
          0x00,
          0x69,
          0x00,
          0x66,
          0x01,
          0x01,
        ]
      : const <int>[
          0x07,
          0x09,
          0x03,
          0x3f,
          0x7f,
          0x00,
          0x69,
          0x00,
          0x65,
          0x01,
          0x01,
        ];
  final typeOffset = _indexOfSublist(bytes, oldTypeSection);
  if (typeOffset < 0) {
    throw StateError('Unable to find async u32 type section in fixture.');
  }
  bytes.replaceRange(
    typeOffset,
    typeOffset + oldTypeSection.length,
    newTypeSection,
  );

  final canonicalKinds = isStream
      ? const <int>[0x0e, 0x0f, 0x10, 0x13, 0x14]
      : const <int>[0x15, 0x16, 0x17, 0x1a, 0x1b];
  final canonicalSearchStart = typeOffset + newTypeSection.length;
  for (final kind in canonicalKinds) {
    final offset = _indexOfSublist(bytes, <int>[
      kind,
      0x00,
    ], start: canonicalSearchStart);
    if (offset < 0) {
      throw StateError('Unable to find canonical ${kind.toRadixString(16)}.');
    }
    bytes[offset + 1] = 0x02;
  }
  return Uint8List.fromList(bytes);
}

/// Rewrites a decoded stream/future memory-copy program to include canonical
/// cancel-read and cancel-write definitions before endpoint drops.
Uint8List asyncMemoryProgramWithCancelDefinitions(
  Uint8List source, {
  required bool isStream,
  required int componentTypeIndex,
  bool cancelIsAsync = true,
}) {
  final bytes = source.toList();
  final writeKind = isStream ? 0x10 : 0x17;
  final cancelReadKind = isStream ? 0x11 : 0x18;
  final cancelWriteKind = isStream ? 0x12 : 0x19;
  final dropReadableKind = isStream ? 0x13 : 0x1a;
  final dropWritableKind = isStream ? 0x14 : 0x1b;
  final oldSection = <int>[
    0x08,
    0x0a,
    0x03,
    writeKind,
    componentTypeIndex,
    0x01,
    0x03,
    0x01,
    dropReadableKind,
    componentTypeIndex,
    dropWritableKind,
    componentTypeIndex,
  ];
  final flag = cancelIsAsync ? 0x01 : 0x00;
  final newSection = <int>[
    0x08,
    0x10,
    0x05,
    writeKind,
    componentTypeIndex,
    0x01,
    0x03,
    0x01,
    cancelReadKind,
    componentTypeIndex,
    flag,
    cancelWriteKind,
    componentTypeIndex,
    flag,
    dropReadableKind,
    componentTypeIndex,
    dropWritableKind,
    componentTypeIndex,
  ];
  final offset = _indexOfSublist(bytes, oldSection);
  if (offset < 0) {
    throw StateError('Unable to find async memory write/drop section.');
  }
  bytes.replaceRange(offset, offset + oldSection.length, newSection);
  return Uint8List.fromList(bytes);
}

